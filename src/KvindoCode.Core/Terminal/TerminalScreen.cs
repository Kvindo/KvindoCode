using System.Text;

namespace KvindoCode.Core.Terminal;

/// <summary>One run of text sharing the same attributes — the unit the UI renders.</summary>
/// <param name="Text">The characters, with no escape sequences in them.</param>
/// <param name="Foreground">The SGR colour as tmux wrote it (<c>38;5;n</c>, <c>31</c>, …), or null for the terminal's default.</param>
public sealed record TerminalRun(string Text, int? Foreground, int? Background, bool Bold, bool Underline, bool Inverse)
{
    public bool SameStyleAs(TerminalRun other) =>
        Foreground == other.Foreground && Background == other.Background
        && Bold == other.Bold && Underline == other.Underline && Inverse == other.Inverse;
}

/// <summary>One row of a pane: a cursor column (for the caret) and its runs.</summary>
public sealed record TerminalLine(List<TerminalRun> Runs, int CursorColumn, bool IsCursorLine)
{
    public string Text => string.Concat(Runs.Select(r => r.Text));
}

/// <summary>A rendered pane.</summary>
public sealed class TerminalScreen
{
    public List<TerminalLine> Lines { get; } = new();
    /// <summary>The row the cursor is on, or -1 when tmux did not report one (a scrollback capture).</summary>
    public int CursorLine { get; internal set; } = -1;
    public int CursorColumn { get; internal set; } = -1;
}

/// <summary>
/// Turns <c>tmux capture-pane -p -e</c> output into lines of styled runs.
/// </summary>
/// <remarks>
/// Deliberately NOT a terminal emulator. tmux already IS one: it has resolved the alternate screen, the scroll
/// regions, the wide characters, the cursor addressing and the wrapping, and what it hands back is a flat picture of
/// a pane with only two kinds of control left in it — SGR (colour/attribute) sequences and a few one-shot escapes
/// (charset selection, cursor visibility). So this parses exactly those and treats everything else as literal text,
/// which is the whole job; a real VT parser here would be re-implementing what produced the input.
///
/// Verify with <c>The_parser_handles_what_tmux_really_emits</c>, whose fixture is generated by a real tmux.
/// </remarks>
public static class TerminalScreenParser
{
    /// <summary>Parse captured pane text. <paramref name="cursorLine"/>/<paramref name="cursorColumn"/> come from tmux's own cursor report (-1 when unknown).</summary>
    public static TerminalScreen Parse(string captured, int cursorLine = -1, int cursorColumn = -1)
    {
        var screen = new TerminalScreen();
        var runs = new List<TerminalRun>();
        var text = new StringBuilder();
        int? fg = null, bg = null;
        bool bold = false, underline = false, inverse = false;

        void Flush()
        {
            if (text.Length == 0) return;
            var run = new TerminalRun(text.ToString(), fg, bg, bold, underline, inverse);
            // merge with the previous run when the style is identical: SGR is re-emitted freely by tmux and one run
            // per escape sequence would make every line hundreds of runs long
            if (runs.Count > 0 && runs[^1].SameStyleAs(run)) runs[^1] = runs[^1] with { Text = runs[^1].Text + run.Text };
            else runs.Add(run);
            text.Clear();
        }

        for (var i = 0; i < captured.Length; i++)
        {
            var c = captured[i];
            if (c == '\n')
            {
                Flush();
                screen.Lines.Add(new TerminalLine(runs, -1, false));
                runs = new List<TerminalRun>();
                continue;
            }
            if (c != '\u001b') { text.Append(c); continue; }

            // ESC ... : an SGR sequence changes the style, every other escape is consumed and ignored
            if (i + 1 < captured.Length && captured[i + 1] == '[')
            {
                var end = captured.IndexOfAny(new[] { 'm', 'h', 'l', 'K', 'A', 'B', 'C', 'D', 'H', 'J', 'r', 't' }, i + 2);
                if (end < 0) { i = captured.Length; continue; }          // unterminated: drop the tail
                var body = captured[(i + 2)..end];
                if (captured[end] == 'm') { Flush(); ApplySgr(body, ref fg, ref bg, ref bold, ref underline, ref inverse); }
                i = end;
                continue;
            }
            // ESC ( B / ESC ) 0 — the charset designator. It is THREE characters (ESC, the introducer, the set), and
            // skipping only two left the 'B' behind as literal text, which is how this was caught: the parser was fed
            // a real capture and "ESC(Bhello" came out as "Bhello". A single-character escape (ESC M, ESC 7) is two.
            i = Math.Min(i + (i + 1 < captured.Length && "()*+-./".Contains(captured[i + 1]) ? 2 : 1), captured.Length - 1);
        }
        Flush();
        screen.Lines.Add(new TerminalLine(runs, -1, false));
        MarkCursor(screen, cursorLine, cursorColumn);
        return screen;
    }

    /// <summary>
    /// Record which row the terminal's cursor is on, and in which column.
    /// </summary>
    /// <remarks>
    /// Separate from the parse because a capture that includes SCROLLBACK has more lines than the visible screen, so
    /// tmux's <c>cursor_y</c> (which counts from the top of the VISIBLE screen) only means something once the caller
    /// knows how many lines came from history. Doing it here rather than guessing at parse time keeps that arithmetic
    /// in one place, and lets a caller with no cursor report (-1) simply not mark one.
    /// </remarks>
    public static void MarkCursor(TerminalScreen screen, int cursorLine, int cursorColumn)
    {
        screen.CursorLine = cursorLine;
        screen.CursorColumn = cursorColumn;
        if (cursorLine < 0 || cursorLine >= screen.Lines.Count) return;
        screen.Lines[cursorLine] = screen.Lines[cursorLine] with { IsCursorLine = true, CursorColumn = cursorColumn };
    }

    /// <summary>Apply one SGR parameter list to the running style.</summary>
    static void ApplySgr(string body, ref int? fg, ref int? bg, ref bool bold, ref bool underline, ref bool inverse)
    {
        if (body.Length == 0) { Reset(ref fg, ref bg, ref bold, ref underline, ref inverse); return; }
        var parts = body.Split(';');
        for (var i = 0; i < parts.Length; i++)
        {
            if (!int.TryParse(parts[i], out var n)) continue;
            switch (n)
            {
                case 0: Reset(ref fg, ref bg, ref bold, ref underline, ref inverse); break;
                case 1: bold = true; break;
                case 4: underline = true; break;
                case 7: inverse = true; break;
                case 22: bold = false; break;
                case 24: underline = false; break;
                case 27: inverse = false; break;
                case 39: fg = null; break;
                case 49: bg = null; break;
                // 30-37 fg, 40-47 bg, 90-97 bright fg, 100-107 bright bg: kept as the raw code, which is what the
                // palette lookup in the UI understands
                case >= 30 and <= 37 or >= 90 and <= 97: fg = n; break;
                case >= 40 and <= 47 or >= 100 and <= 107: bg = n; break;
                // 38;5;n / 38;2;r;g;b (and the 48 form): the extended colours, with their parameters consumed
                case 38 or 48:
                    if (i + 1 >= parts.Length) break;
                    if (parts[i + 1] == "5" && i + 2 < parts.Length && int.TryParse(parts[i + 2], out var idx))
                    {
                        if (n == 38) fg = 256 + idx; else bg = 256 + idx;
                        i += 2;
                    }
                    else if (parts[i + 1] == "2" && i + 4 < parts.Length
                             && int.TryParse(parts[i + 2], out var r) && int.TryParse(parts[i + 3], out var g) && int.TryParse(parts[i + 4], out var b))
                    {
                        // packed so the UI can tell a truecolor value from a palette index
                        var packed = 1_000_000 + ((r & 0xFF) << 16) + ((g & 0xFF) << 8) + (b & 0xFF);
                        if (n == 38) fg = packed; else bg = packed;
                        i += 4;
                    }
                    break;
            }
        }

        static void Reset(ref int? fg, ref int? bg, ref bool bold, ref bool underline, ref bool inverse)
        { fg = null; bg = null; bold = false; underline = false; inverse = false; }
    }
}
